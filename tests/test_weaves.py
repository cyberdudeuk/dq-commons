"""Weaves to other platforms, the vendor directory and their wiring (v2.13)."""
import json
import re
import subprocess
import sys
import unittest
from pathlib import Path

import yaml

from dqkit import mcp_server, rules, weaves

ROOT = Path(__file__).resolve().parent.parent
LIB = sorted((ROOT / "rules" / "library").glob("*.yaml"))
V = yaml.safe_load((ROOT / "knowledge" / "vendors.yaml").read_text(encoding="utf-8"))


def spec_of(f):
    return rules.expand_valuesets(yaml.safe_load(f.read_text(encoding="utf-8")))


class WeaveTests(unittest.TestCase):
    def test_every_target_on_every_library_file(self):
        for f in LIB:
            for t in weaves.TARGETS:
                out = weaves.weave(spec_of(f), t)
                self.assertIn("generated by dqkit weaves", out, (f.name, t))
                self.assertTrue(out.endswith("\n"))

    def test_nothing_silently_dropped(self):
        """Every rule id appears in the output, either exported or listed as not exported."""
        for f in LIB:
            spec = spec_of(f)
            for t in weaves.TARGETS:
                out = weaves.weave(spec, t).lower()
                for r in spec["rules"]:
                    self.assertTrue(str(r["id"]).lower() in out or weaves._slug(r["id"]) in out, (f.name, t, r["id"]))

    def test_known_outputs(self):
        spec = {"asset": {"id": "t", "importance": 3}, "rules": [
            {"id": "R1", "check": "not_null", "column": "a"},
            {"id": "R2", "check": "in_set", "column": "b", "values": ["x", "y"]},
            {"id": "R3", "check": "range", "column": "c", "min": 0, "max": 10}]}
        self.assertIn('Completeness "a" >=', weaves.weave(spec, "glue"))
        self.assertIn('ColumnValues "b" in ["x", "y"]', weaves.weave(spec, "glue"))
        self.assertIn("nonNullExpectation: {}", weaves.weave(spec, "dataplex"))
        self.assertIn("- accepted_values:", weaves.weave(spec, "dbt"))
        self.assertIn("missing_percent(a)", weaves.weave(spec, "soda"))
        self.assertIn("SNOWFLAKE.CORE.NULL_COUNT", weaves.weave(spec, "snowflake"))
        self.assertIn("CONSTRAINT r3 EXPECT (`c` >= 0 AND `c` <= 10)", weaves.weave(spec, "databricks"))
        self.assertIn('.isContainedIn("b", ["x", "y"]', weaves.weave(spec, "deequ"))
        self.assertIn("columnValuesToBeBetween", weaves.weave(spec, "openmetadata"))
        self.assertIn("type: not_null", weaves.weave(spec, "datahub"))
        self.assertIn("custom_sql:", weaves.weave(spec, "montecarlo"))
        self.assertIn("WHERE NOT (\"a\" IS NOT NULL)", weaves.weave(spec, "sql"))

    def test_sql_quotes_are_escaped(self):
        spec = {"asset": {"id": "t"}, "rules": [{"id": "R1", "check": "in_set", "column": 'we"ird', "values": ["o'neil"]}]}
        out = weaves.weave(spec, "sql")
        self.assertIn('"we""ird"', out)
        self.assertIn("'o''neil'", out)

    def test_unknown_target(self):
        with self.assertRaises(ValueError):
            weaves.weave({"asset": {"id": "t"}, "rules": []}, "nope")

    def test_crosswalk_covers_every_check_and_target(self):
        cw = weaves.crosswalk()
        self.assertEqual(set(cw), set(rules.CHECKS))
        for row in cw.values():
            self.assertEqual(set(row), set(weaves.TARGETS))
            self.assertTrue(set(row.values()) <= {"native", "sql", "none"})
        self.assertEqual(cw["not_null"]["glue"], "native")
        self.assertEqual(cw["identifier"]["glue"], "none")

    def test_cli_export(self):
        out = subprocess.run([sys.executable, "-m", "dqkit", "export", str(LIB[0]), "--to", "dbt"], capture_output=True, text=True, cwd=ROOT)
        self.assertEqual(out.returncode, 0, out.stderr)
        self.assertIn("version: 2", out.stdout)

    def test_mcp_tool(self):
        self.assertIn("weave_rules", [t["name"] for t in mcp_server.TOOLS])
        res = mcp_server.call_tool("weave_rules", {"rules_yaml": LIB[0].read_text(encoding="utf-8"), "target": "soda"})
        self.assertIn("checks for", res["text"])


class VendorDataTests(unittest.TestCase):
    def test_shape_and_sources(self):
        reps = {r["id"] for r in V["reports"]}
        targets = {t["id"] for t in V["weave_targets"]}
        self.assertEqual(targets, set(weaves.TARGETS))
        ids = [v["id"] for v in V["vendors"]]
        self.assertEqual(len(ids), len(set(ids)))
        for v in V["vendors"]:
            self.assertRegex(v["checked"], r"^\d{4}-\d{2}-\d{2}$", v["id"])
            self.assertIn(v["weave"], ("native", "sql", "mapping"), v["id"])
            if v["weave"] == "native":
                self.assertIn(v["weave_target"], targets | {"great_expectations"}, v["id"])
            for r in v.get("recognition", []):
                self.assertIn(r["report"], reps, v["id"])
                self.assertTrue(r["source"].startswith("https://"), v["id"])
            ai = v.get("ai", {})
            self.assertIn(ai.get("mcp", "not-found"), V["legend"]["mcp"], v["id"])
            if ai.get("mcp") in ("ga", "preview", "open-source"):
                self.assertTrue(ai.get("sources"), f"{v['id']}: an MCP claim needs a source")
            for g in v.get("github", []):
                self.assertRegex(g["repo"], r"^[A-Za-z0-9-]+/[A-Za-z0-9._-]+$", v["id"])

    def test_every_2026_mq_vendor_is_listed(self):
        mq = next(r for r in V["reports"] if r["id"] == "gartner-adq-2026")
        names = " ".join(v["name"] for v in V["vendors"]).lower()
        for n in mq["vendors"]:
            key = re.sub(r"\s*\(.*\)|\s+software$", "", n, flags=re.I).lower()
            self.assertIn(key, names, n)

    def test_page_registered(self):
        src = (ROOT / "scripts" / "build_dq_portal.py").read_text(encoding="utf-8")
        self.assertIn('("connectors",', src)
        self.assertIn("__K_VENDORS__", (ROOT / "portal" / "src" / "pages" / "connectors.html").read_text(encoding="utf-8"))


if __name__ == "__main__":
    unittest.main()


