"""Generate the GitHub issue forms for surveys and maturity sharing from the knowledge base (D-GH-02).

Usage: python scripts/gen_issue_forms.py [--check]

Surveys (knowledge/surveys.yaml) and the maturity self-assessment (knowledge/maturity.yaml) are answered on
GitHub, so the Commons needs no other service. One form per survey is written to .github/ISSUE_TEMPLATE/,
with the same question ids the portal uses, so the portal can pre-fill it and the portal build can count the
answers. Free-text questions are left out of the GitHub forms: GitHub issues are public at once, and free text
must never be published without moderation. Use the contact form for comments instead.
--check exits 1 if the committed forms are out of date (a test runs this).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / ".github" / "ISSUE_TEMPLATE"
NOTICE = ("**Before you answer.** GitHub issues are public as soon as you submit, and show your GitHub username. "
          "Answer for your organisation only if you are happy for that to be seen, or ask a colleague to submit for the team. "
          "Never include names, email addresses or any other personal data. The Commons publishes only totals, and hides "
          "any count under 5. To withdraw, use the contact form (Withdraw my contribution).")


RESERVED = {"None": "None of these"}  # GitHub reserves "None" in dropdowns; the portal build maps it back


def opts(q: dict) -> list:
    return [RESERVED.get(o, o) for o in q["options"]]


def q_field(q: dict) -> dict:
    a = {"label": q["q"]}
    if q["type"] in ("single", "band"):
        return {"type": "dropdown", "id": q["id"], "attributes": {**a, "options": opts(q)}}
    if q["type"] == "multi":
        return {"type": "dropdown", "id": q["id"], "attributes": {**a, "multiple": True, "options": opts(q)}}
    if q["type"] == "rating":
        low, high = q.get("low", "very poor"), q.get("high", "very good")
        return {"type": "dropdown", "id": q["id"], "attributes": {**a, "description": f"1 is {low}, 5 is {high}.",
                                                                  "options": ["1", "2", "3", "4", "5", "Don't know"]}}
    return {}


def forms() -> dict:
    S = yaml.safe_load((ROOT / "knowledge" / "surveys.yaml").read_text(encoding="utf-8"))
    M = yaml.safe_load((ROOT / "knowledge" / "maturity.yaml").read_text(encoding="utf-8"))
    out = {}
    for i, s in enumerate(S["surveys"]):
        body = [{"type": "markdown", "attributes": {"value": f"{s['purpose']}\n\n{NOTICE}"}}]
        body += [f for f in (q_field(q) for q in s["questions"]) if f]
        out[f"7{i}-survey-{s['id']}.yml"] = {"name": f"Survey: {s['title']}", "description": f"About {s['minutes']} minutes. Totals only are published.",
                                            "title": f"[Survey] {s['title']}", "labels": ["survey-response", f"survey:{s['id']}"], "body": body}
    levels = [f"{l['n']} {l['name']}" for l in M["levels"]]
    body = [{"type": "markdown", "attributes": {"value": "Share your maturity levels so others can compare. The portal's self-assessment fills this in for you.\n\n" + NOTICE}},
            q_field({**S["shared"]["org_type"], "type": "single"}), q_field({**S["shared"]["nation"], "type": "single"})]
    body += [{"type": "dropdown", "id": t["id"], "attributes": {"label": t["name"], "options": levels}, "validations": {"required": True}} for t in M["themes"]]
    out["6-maturity-share.yml"] = {"name": "Share maturity levels (benchmark)", "description": "Your 8 theme levels, for the benchmark. Totals only are published.",
                                   "title": "[Maturity] Levels shared", "labels": ["maturity-share"], "body": body}
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    stale = []
    for name, form in forms().items():
        text = "# Generated by scripts/gen_issue_forms.py from the knowledge base. Edit the knowledge file, not this.\n" + \
               yaml.safe_dump(form, sort_keys=False, allow_unicode=True, width=200)
        f = OUT / name
        if a.check:
            if not f.exists() or f.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            f.write_text(text, encoding="utf-8")
    if a.check and stale:
        print("Out of date: " + ", ".join(stale) + ". Run python scripts/gen_issue_forms.py")
        return 1
    print("Issue forms are current." if a.check else f"Wrote {len(forms())} issue forms.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
